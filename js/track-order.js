let currentUser = null;

const ORDER_FLOW = [
  { key: "PLACED", label: "Order Placed", icon: "shopping_cart", desc: "Your order has been placed successfully" },
  { key: "DELIVERED", label: "Out for Delivery", icon: "local_shipping", desc: "Your order is on the way to you" },
  { key: "RECEIVED", label: "Received", icon: "done_all", desc: "Order has been delivered to your desk" },
  { key: "BILLED", label: "Bill Generated", icon: "receipt", desc: "Bill has been generated by the canteen" },
  { key: "PAID", label: "Payment Done", icon: "payments", desc: "Payment has been confirmed" },
  { key: "COMPLETED", label: "Completed", icon: "check_circle", desc: "Your order has been completed" }
];

function getOrderIdFromUrl() {
  return new URLSearchParams(window.location.search).get("id");
}

function renderSubnav(role) {
  const subnav = document.getElementById("subnav");
  if (role === "ADMIN") {
    subnav.innerHTML = '<a href="admin.html"><span class="material-symbols-outlined">dashboard</span> Dashboard</a>' +
      '<a href="my-orders.html"><span class="material-symbols-outlined">receipt_long</span> Back to Orders</a>';
  }
}

function buildTracker(currentStatus) {
  const statusOrder = ORDER_FLOW.map(function(s){ return s.key; });
  const currentIdx = statusOrder.indexOf(currentStatus);
  const progress = currentIdx >= 0 ? ((currentIdx) / (ORDER_FLOW.length - 1)) * 100 : 0;

  let stepsHtml = ORDER_FLOW.map(function(step, i) {
    let cls = "";
    if (i < currentIdx) cls = "completed";
    else if (i === currentIdx) cls = "active";
    return '<div class="tracker-step ' + cls + '">' +
      '<div class="tracker-dot">' +
        '<span class="material-symbols-outlined">' + step.icon + '</span>' +
      '</div>' +
      '<div class="tracker-label">' + step.label + '</div>' +
    '</div>';
  }).join("");

  return '<div class="order-tracker">' +
    '<div class="order-tracker-progress" style="width:' + progress + '%;"></div>' +
    stepsHtml +
  '</div>';
}

function buildStatusMessage(status) {
  const step = ORDER_FLOW.find(function(s){ return s.key === status; });
  if (!step) return "";
  const idx = ORDER_FLOW.indexOf(step);
  const nextStep = ORDER_FLOW[idx + 1];
  let msg = '<div class="track-status-msg">';
  msg += '<span class="material-symbols-outlined track-status-icon">' + step.icon + '</span>';
  msg += '<div class="track-status-text">';
  msg += '<div class="track-status-title">' + step.label + '</div>';
  msg += '<div class="track-status-desc">' + step.desc + '</div>';
  if (nextStep) {
    msg += '<div class="track-status-next">Next: ' + nextStep.label + '</div>';
  } else {
    msg += '<div class="track-status-next success-text">Order is fully complete!</div>';
  }
  msg += '</div></div>';
  return msg;
}

function buildItemsList(items) {
  if (!items || !items.length) return "";
  const rows = items.map(function(item) {
    const imgSrc = getFoodImage(item.itemName, "");
    return '<div class="track-item">' +
      '<img class="track-item-img" src="' + imgSrc + '" alt="' + escapeHtml(item.itemName) + '" onerror="handleImageError(this)">' +
      '<div class="track-item-info">' +
        '<div class="track-item-name">' + escapeHtml(item.itemName) + '</div>' +
        '<div class="track-item-meta">Qty: ' + item.quantity + ' × ' + formatMoney(item.unitPrice) + '</div>' +
      '</div>' +
      '<div class="track-item-total">' + formatMoney(item.amount) + '</div>' +
    '</div>';
  }).join("");
  return '<div class="panel"><h2><span class="material-symbols-outlined" style="font-size:20px;vertical-align:middle;">shopping_bag</span> Items Ordered</h2><div class="track-items">' + rows + '</div></div>';
}

function renderTrackOrder(order) {
  const container = document.getElementById("trackContent");
  const isComplete = order.status === "COMPLETED";

  let html = '<div style="display:flex;align-items:center;justify-content:space-between;margin-bottom:24px;flex-wrap:wrap;gap:12px;">' +
    '<h1 style="margin:0;"><span class="material-symbols-outlined" style="font-size:28px;vertical-align:middle;">local_shipping</span> Track Order #' + order.id + '</h1>' +
    '<a href="my-orders.html" class="btn btn-outline btn-sm"><span class="material-symbols-outlined">arrow_back</span> All Orders</a>' +
  '</div>';

  html += '<div class="panel">' + buildStatusMessage(order.status) + '</div>';
  html += '<div class="panel"><h2><span class="material-symbols-outlined" style="font-size:20px;vertical-align:middle;">timeline</span> Order Progress</h2>' + buildTracker(order.status) + '</div>';

  html += '<div class="track-info-grid">' +
    '<div class="panel track-info-card"><span class="material-symbols-outlined" style="font-size:20px;color:var(--primary);">schedule</span><div><div class="track-info-label">Order Time</div><div class="track-info-value">' + formatDateTime(order.orderTime) + '</div></div></div>' +
    '<div class="panel track-info-card"><span class="material-symbols-outlined" style="font-size:20px;color:var(--primary);">location_on</span><div><div class="track-info-label">Delivery Location</div><div class="track-info-value">' + escapeHtml(order.deliveryLocationName) + '</div></div></div>' +
    '<div class="panel track-info-card"><span class="material-symbols-outlined" style="font-size:20px;color:var(--primary);">payments</span><div><div class="track-info-label">Total Amount</div><div class="track-info-value" style="font-size:20px;font-weight:800;color:var(--primary);">' + formatMoney(order.totalAmount) + '</div></div></div>' +
    '<div class="panel track-info-card"><span class="material-symbols-outlined" style="font-size:20px;color:var(--primary);">info</span><div><div class="track-info-label">Status</div><div class="track-info-value"><span class="status-pill ' + order.status + '">' + order.status + '</span></div></div></div>' +
  '</div>';

  html += buildItemsList(order.items);

  if (order.status === "COMPLETED") {
    html += '<div class="panel" style="text-align:center;padding:32px;">' +
      '<span class="material-symbols-outlined" style="font-size:48px;color:var(--success);">check_circle</span>' +
      '<h2 style="margin:12px 0 4px;">Order Complete!</h2>' +
      '<p style="color:var(--muted);">Thank you for ordering with Desk2Dine.</p>' +
      '<a href="faculty.html" class="btn btn-primary" style="margin-top:16px;">' +
        '<span class="material-symbols-outlined">add_shopping_cart</span> Order Again' +
      '</a>' +
    '</div>';
  }

  container.innerHTML = html;
}

async function init() {
  currentUser = await requireAuth(["FACULTY"]);
  if (!currentUser) return;
  refreshNotifBadge();

  const id = getOrderIdFromUrl();
  if (!id) {
    document.getElementById("trackContent").innerHTML =
      '<div class="empty-state"><div class="empty-icon"><span class="material-symbols-outlined">search</span></div><div class="big">No order specified</div><p>Please select an order to track.</p><a href="my-orders.html" class="btn btn-primary" style="margin-top:16px;">View My Orders</a></div>';
    return;
  }

  try {
    const order = await api("/api/orders/" + id);
    renderTrackOrder(order);
  } catch (e) {
    showToast(e.message, true);
    document.getElementById("trackContent").innerHTML =
      '<div class="empty-state"><div class="empty-icon"><span class="material-symbols-outlined">error</span></div><div class="big">Order not found</div><p>' + e.message + '</p><a href="my-orders.html" class="btn btn-primary" style="margin-top:16px;">View My Orders</a></div>';
  }
}

async function refreshNotifBadge() {
  try {
    const result = await api("/api/notifications/unread-count");
    const badge = document.getElementById("notifBadge");
    if (result.unread > 0) {
      badge.style.display = "flex";
      badge.textContent = result.unread > 9 ? "9+" : result.unread;
    }
  } catch (e) { /* non-critical */ }
}

init();
