package com.desk2dine.util;

/**
 * Every controller returns this same envelope shape so the frontend has
 * one consistent contract to parse: {success, message, data}. Without
 * this, some endpoints would return bare objects and others would
 * return errors in different shapes, which is exactly the kind of
 * inconsistency that makes a frontend brittle.
 */
public class ApiResponse<T> {

    private final boolean success;
    private final String message;
    private final T data;

    private ApiResponse(boolean success, String message, T data) {
        this.success = success;
        this.message = message;
        this.data = data;
    }

    public static <T> ApiResponse<T> ok(T data) {
        return new ApiResponse<>(true, "OK", data);
    }

    public static <T> ApiResponse<T> ok(String message, T data) {
        return new ApiResponse<>(true, message, data);
    }

    public static <T> ApiResponse<T> error(String message) {
        return new ApiResponse<>(false, message, null);
    }

    public boolean isSuccess() {
        return success;
    }

    public String getMessage() {
        return message;
    }

    public T getData() {
        return data;
    }
}
